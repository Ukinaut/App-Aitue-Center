test('Migración GB conserva cantidades y atribuye los consumos anteriores a su conexión',()=>{
  const db=new DatabaseSync(':memory:');
  try{
    db.exec(`CREATE TABLE users(id TEXT PRIMARY KEY,role TEXT); INSERT INTO users VALUES ('owner','controlador'),('root','superadmin');
    CREATE TABLE apps(id TEXT PRIMARY KEY,name TEXT,description TEXT,url TEXT,color TEXT);
    CREATE TABLE gb_sims(id TEXT PRIMARY KEY,number TEXT UNIQUE,operator TEXT,capacity INTEGER,owner_id TEXT,created_at TEXT);
    CREATE TABLE gb_devices(id TEXT PRIMARY KEY,kit TEXT UNIQUE,name TEXT,sim_id TEXT UNIQUE,capacity INTEGER,allocated INTEGER,owner_id TEXT,active INTEGER,created_at TEXT);
    CREATE TABLE gb_usage(id TEXT PRIMARY KEY,device_id TEXT,amount INTEGER,date TEXT,note TEXT,actor_id TEXT,created_at TEXT);
    INSERT INTO gb_sims VALUES ('sim','0001','Operador',100000,'owner','2026-01-01');
    INSERT INTO gb_devices VALUES ('mobile','KIT-M','Móvil','sim',0,80000,'owner',1,'2026-01-01'),('sat','KIT-S','Satelital',NULL,500000,300000,'root',1,'2026-01-01');
    INSERT INTO gb_usage VALUES ('u1','mobile',12500,'2026-01-01','','owner','2026-01-01'),('u2','sat',50000,'2026-01-01','','owner','2026-01-01');`);
    initializeGb(db);initializeGb(db);
    assert.equal(db.prepare('SELECT source FROM gb_usage WHERE id=?').get('u1').source,'sim');
    assert.equal(db.prepare('SELECT source FROM gb_usage WHERE id=?').get('u2').source,'satellite');
    assert.deepEqual({...db.prepare('SELECT satellite_enabled,satellite_allocated,sim_allocated FROM gb_devices WHERE id=?').get('mobile')},{satellite_enabled:0,satellite_allocated:0,sim_allocated:80000});
    assert.deepEqual({...db.prepare('SELECT satellite_enabled,satellite_allocated,sim_allocated FROM gb_devices WHERE id=?').get('sat')},{satellite_enabled:1,satellite_allocated:300000,sim_allocated:0});
    assert.equal(db.prepare('SELECT SUM(amount) total FROM gb_usage').get().total,62500);
    assert.equal(db.prepare('SELECT controller_id FROM gb_devices WHERE id=?').get('mobile').controller_id,'owner');
    assert.equal(db.prepare('SELECT controller_id FROM gb_devices WHERE id=?').get('sat').controller_id,null);
  }finally{db.close();}
});
