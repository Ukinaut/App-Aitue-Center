import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

test('Autenticación, jerarquía, aislamiento de ramas y revocación en el servidor', async t => {
  const dir = mkdtempSync(path.join(tmpdir(),'aitue-test-'));
  const serverPath = fileURLToPath(new URL('../server.mjs',import.meta.url));
  const child = spawn(process.execPath,[serverPath],{env:{...process.env,PORT:'0',DATA_DIR:dir},stdio:['ignore','pipe','pipe']});
  const stopped = new Promise(resolve=>child.once('exit',resolve));
  t.after(async()=>{child.kill();await stopped;if(path.basename(dir).startsWith('aitue-test-')&&path.dirname(dir)===tmpdir())rmSync(dir,{recursive:true,force:true});});
  let stderr='';child.stderr.on('data',x=>stderr+=x);
  const origin=await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(new Error('No inició el servidor. '+stderr)),10000);child.stdout.on('data',d=>{const url=d.toString().match(/http:\/\/[^\s]+/);if(url){clearTimeout(timer);resolve(url[0]);}});child.once('error',reject);});
  const client=()=>({cookie:'',async call(route,method='GET',body,headers={}){const res=await fetch(origin+'/api/'+route,{method,headers:{'Content-Type':'application/json','X-Aitue-Request':'1',Cookie:this.cookie,...headers},...(body?{body:JSON.stringify(body)}:{})});const cookie=res.headers.get('set-cookie');if(cookie)this.cookie=cookie.split(';')[0];return {status:res.status,data:await res.json(),headers:res.headers};}});
  const root=client(),admin=client(),controller=client(),final=client(),other=client(),secondRoot=client();
  const pw='Aitue-test-password-2026';
  const create=async(c,name,role,apps=[],can_create=false)=>c.call('users','POST',{name,email:name+'@test.example',password:pw,role,apps,can_create});
  const find=async(c,name)=>(await c.call('dashboard')).data.users.find(x=>x.name===name);
  assert.equal((await root.call('dashboard')).status,401);
  assert.equal((await root.call('status')).data.needsSetup,true);
  assert.equal((await root.call('setup','POST',{name:'Root',email:'root@test.example',password:'short'})).status,400);
  assert.equal((await root.call('setup','POST',{name:'Root',email:'root@test.example',password:pw})).status,201);
  assert.equal((await other.call('setup','POST',{name:'Intruder',email:'intruder@test.example',password:pw})).status,403);
  assert.equal((await other.call('login','POST',{email:'root@test.example',password:'wrong'})).status,401);
  assert.equal((await create(root,'SecondRoot','superadmin')).status,201);
  const secondRootUser=await find(root,'SecondRoot');
  assert.equal(secondRootUser.parent_id,null);
  assert.equal(secondRootUser.can_create,true);
  assert.equal((await secondRoot.call('login','POST',{email:'secondroot@test.example',password:pw})).status,200);
  const primaryRoot=(await secondRoot.call('dashboard')).data.users.find(u=>u.name==='Root');
  assert.ok(primaryRoot);
  assert.equal((await secondRoot.call(`users/${secondRootUser.id}`,'PATCH',{active:false})).status,403);
  assert.equal((await secondRoot.call(`users/${primaryRoot.id}`,'PATCH',{active:false})).status,200);
  assert.equal((await secondRoot.call('dashboard')).status,200);
  assert.equal((await root.call('dashboard')).status,401);
  assert.equal((await secondRoot.call(`users/${primaryRoot.id}`,'PATCH',{active:true})).status,200);
  assert.equal((await root.call('login','POST',{email:'root@test.example',password:pw})).status,200);
  assert.equal((await root.call('apps','POST',{name:'Gestión',description:'App de prueba',url:'javascript:alert(1)'})).status,400);
  assert.equal((await root.call('apps','POST',{name:'Gestión',description:'App de prueba',url:'https://example.com/gestion'})).status,201);
  assert.equal((await root.call('apps','POST',{name:'Reportes',description:'Otra app',url:'https://example.com/reportes'})).status,201);
  const apps=(await root.call('dashboard')).data.apps;
  const management=apps.find(x=>x.name==='Gestión').id, reports=apps.find(x=>x.name==='Reportes').id;
  assert.equal((await create(root,'Admin','admin',[management],true)).status,201);
  assert.equal((await create(root,'Other','admin',[reports],true)).status,201);
  assert.equal((await admin.call('login','POST',{email:'ADMIN@test.example',password:pw})).status,200);
  assert.equal((await other.call('login','POST',{email:'other@test.example',password:pw})).status,200);
  assert.equal((await create(admin,'Escalation','superadmin',[management],true)).status,403);
  assert.equal((await admin.call(`users/${secondRootUser.id}`,'PATCH',{active:false})).status,403);
  assert.equal((await create(admin,'Unauthorized','controlador',[reports],true)).status,403);
  assert.equal((await create(admin,'Controller','controlador',[management],true)).status,201);
  assert.equal((await controller.call('login','POST',{email:'controller@test.example',password:pw})).status,200);
  assert.equal((await create(controller,'Final','usuario',[management],true)).status,403);
  assert.equal((await create(controller,'Final','usuario',[management],false)).status,201);
  assert.equal((await final.call('login','POST',{email:'final@test.example',password:pw})).status,200);
  assert.equal((await create(final,'Child','usuario',[],false)).status,403);
  assert.equal((await final.call('dashboard')).data.users.length,1);
  assert.equal((await final.call(`apps/${reports}/launch`)).status,403);
  assert.equal((await final.call(`apps/${management}/launch`)).status,200);
  const user=await find(root,'Final'), controllerUser=await find(root,'Controller'), adminUser=await find(root,'Admin');
  assert.equal((await other.call(`users/${user.id}`,'PATCH',{active:false,apps:[]})).status,403);
  assert.equal((await other.call('dashboard')).data.users.some(u=>u.id===user.id),false);
  assert.equal((await admin.call('apps','POST',{name:'Blocked',description:'',url:'https://example.com'})).status,403);
  assert.equal((await root.call('users','POST',{}, {'X-Aitue-Request':''})).status,403);
  assert.equal((await root.call('users','POST',{}, {Origin:'https://attacker.example'})).status,403);
  assert.equal((await root.call(`users/${adminUser.id}`,'PATCH',{apps:[],can_create:false})).status,200);
  assert.deepEqual((await find(root,'Final')).apps,[]);
  assert.deepEqual((await find(root,'Controller')).apps,[]);
  assert.equal((await find(root,'Controller')).can_create,false);
  assert.equal((await controller.call('dashboard')).status,401);
  assert.equal((await admin.call('dashboard')).status,401);
  await admin.call('login','POST',{email:'admin@test.example',password:pw});
  assert.equal((await create(admin,'NoDelegation','usuario',[])).status,403);
  assert.equal((await admin.call(`users/${controllerUser.id}`,'PATCH',{apps:[],can_create:false})).status,200);
  assert.equal((await root.call(`users/${adminUser.id}`,'PATCH',{active:false})).status,200);
  assert.equal((await find(root,'Final')).active,false);
  assert.equal((await final.call('login','POST',{email:'final@test.example',password:pw})).status,401);
  assert.equal((await root.call(`users/${user.id}`,'PATCH',{active:true})).status,400);
  assert.equal((await root.call(`users/${adminUser.id}`,'PATCH',{active:true})).status,200);
  assert.equal((await find(root,'Final')).active,false);
  assert.equal((await root.call('logout','POST',{})).status,200);
  assert.equal((await root.call('dashboard')).status,401);
});
